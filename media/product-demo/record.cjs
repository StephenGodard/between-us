// Requires Playwright, Chrome, and the local app at https://localhost:8443.
// Run from the repository root; serve that root on port 4174 first.
const {chromium}=require('playwright');
const fs=require('node:fs');
const path=require('node:path');
const fast=process.env.PREFLIGHT==='1';
const out=path.join(__dirname,fast?'preflight':'capture');
fs.mkdirSync(out,{recursive:true});
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 const context=await browser.newContext({ignoreHTTPSErrors:true,viewport:{width:1920,height:1080},deviceScaleFactor:1,recordVideo:{dir:out,size:{width:1920,height:1080}}});
 const origin=Date.now();
 const page=await context.newPage();
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:4174/media/product-demo/stage.html');
 const a=page.frameLocator('#a'),b=page.frameLocator('#b');
 await a.getByText('Prêt pour un échange',{exact:true}).waitFor();
 await b.getByText('Prêt pour un échange',{exact:true}).waitFor();
 await page.evaluate(()=>document.fonts.ready);
 await page.waitForTimeout(500);
 const start=Date.now();
 const at=async seconds=>{if(fast)return;const ms=start+seconds*1000-Date.now();if(ms>0)await page.waitForTimeout(ms)};
 const scene=async(...args)=>page.evaluate(args=>window.scene(...args),args);
 const snap=async name=>page.screenshot({path:path.join(out,name+'.png')});
 await page.evaluate(()=>{const start=performance.now();setInterval(()=>document.querySelector('#progress').style.width=Math.min(100,(performance.now()-start)/1200)+'%',100)});
 await snap('00-title');
 await at(5);await scene('landing','01 / L’idée','Un espace pour se parler, le temps d’une conversation.');
 await snap('01-landing');
 await at(13);await scene('landing','01 / L’idée','Parfois, on a besoin de parler. Parfois, on peut écouter.');
 await at(20);await scene('pair','02 / Proposer un sujet','Tout commence par un sujet que l’on souhaite partager.','Deux vues de l’application locale, reliées au même serveur.');
 await at(24);await a.getByLabel('Votre sujet',{exact:true}).pressSequentially('Traverser un deuil',{delay:fast?0:125});
 await at(30);await a.getByRole('button',{name:'Ouvrir mon sujet'}).press('Enter');
 await a.getByText('En attente d’une personne',{exact:true}).waitFor();
 await snap('02-waiting');
 await at(36);await scene('pair','03 / Choisir d’écouter','Une autre personne choisit le sujet auquel elle souhaite répondre.');
 await b.getByRole('button',{name:'Je suis disponible pour écouter'}).press('Enter');
 await at(43);await snap('03-subject');
 await at(46);await b.getByRole('button',{name:'Rejoindre : Traverser un deuil',exact:true}).press('Enter');
 await a.getByText('Vous êtes deux pour échanger',{exact:true}).waitFor();
 await b.getByText('Vous êtes deux pour échanger',{exact:true}).waitFor();
 await at(51);await scene('pair','04 / Échanger','Un premier mot suffit.');
 const send=async(frame,other,text)=>{await frame.getByLabel('Votre message',{exact:true}).pressSequentially(text,{delay:fast?0:45});await frame.getByRole('button',{name:'Envoyer',exact:true}).press('Enter');await other.getByText(text,{exact:true}).waitFor();};
 await at(53);await send(a,b,'Depuis le décès de mon père, les dimanches sont difficiles.');
 await at(63);await send(b,a,'Qu’est-ce qui te manque le plus ces jours-là ?');
 await at(72);await scene('pair','04 / Échanger','Écouter, répondre, laisser une place à l’autre.');
 await send(a,b,'Nos appels. On parlait de tout et de rien.');
 await at(82);await send(b,a,'Tu veux me raconter un de ces moments ?');
 await at(90);await snap('04-conversation');
 await at(94);await scene('pair','05 / Terminer','Quand le moment se termine, on clôt la conversation.');
 await at(100);await a.getByRole('button',{name:'Terminer l’échange',exact:true}).press('Enter');
 for(const frame of [a,b]){await frame.getByText('Cet échange est terminé. Les messages ne sont plus affichés.',{exact:true}).waitFor();if(await frame.getByText('Nos appels. On parlait de tout et de rien.',{exact:true}).count())throw Error('Message still visible after closure');}
 await scene('pair','05 / Terminer','Les messages ne sont plus visibles pour les deux participants.');
 await snap('05-closed');
 await at(110);await page.evaluate(()=>window.finish());await snap('06-outro');
 await at(121);
 const video=page.video();await context.close();
 const raw=await video.path();
 fs.writeFileSync(path.join(__dirname,fast?'preflight.json':'capture.json'),JSON.stringify({raw,startOffsetSeconds:(start-origin)/1000,duration:120,errors,checks:['Two live clients connected','Four messages received by the other participant','Closure notice on both clients','Conversation messages absent after closure']},null,2));
 await browser.close();console.log('Capture complete:',raw);
})().catch(e=>{console.error(e);process.exit(1)});
